import json
import logging
import re
import time
from typing import Any, Dict, Optional
from app.core.config import settings

logger = logging.getLogger("fragment_first.llm")


class _PruneResponse:
    def __init__(self, payload: Dict[str, Any]):
        choices = payload.get("choices")
        if not choices or not choices[0].get("message", {}).get("content"):
            raise ValueError("Prune response did not contain a text completion.")
        self.text = choices[0]["message"]["content"]


class _PruneGeminiCompatibleClient:
    def __init__(self, api_key: str):
        from prune import Gemini

        self.client = Gemini(prune_api_key=api_key)

    def generate_content(self, prompt: str) -> _PruneResponse:
        response = self.client.generate_content(
            model="gemini-1.5-flash",
            messages=[{"role": "user", "content": prompt}],
        )
        return _PruneResponse(response)


class LLMService:
    def __init__(self):
        self.api_key = settings.PRUNE_API_KEY
        self.demo_mode = settings.DEMO_MODE or not bool(self.api_key)
        self.client = None
        self._init_client()

    def _init_client(self):
        if not self.demo_mode and self.api_key:
            try:
                self.client = _PruneGeminiCompatibleClient(self.api_key)
                logger.info("Prune LLM client successfully initialized.")
            except Exception as e:
                logger.warning(f"Failed to initialize Prune client: {e}. Falling back to DEMO MODE.")
                self.demo_mode = True
        else:
            self.demo_mode = True
            logger.info("Running LLMService in DEMO MODE (API key not configured or DEMO_MODE enabled).")

    def is_demo_mode(self) -> bool:
        return self.demo_mode

    def _clean_json_response(self, text: str) -> str:
        """Strips markdown code blocks and whitespace around JSON output."""
        text = text.strip()
        match = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", text)
        if match:
            return match.group(1).strip()
        return text

    def generate_text(self, prompt: str, system_instruction: str = "") -> str:
        """Generates raw text response with error handling and retry."""
        if self.demo_mode:
            return f"[DEMO MODE RESPONSE] Mock LLM output for prompt: {prompt[:80]}..."

        full_prompt = f"{system_instruction}\n\nUser Request:\n{prompt}" if system_instruction else prompt
        
        for attempt in range(3):
            try:
                response = self.client.generate_content(full_prompt)
                if response and response.text:
                    return response.text.strip()
            except Exception as e:
                logger.warning(f"Gemini API attempt {attempt + 1} failed: {e}")
                time.sleep(1)
                
        logger.error("Gemini API calls failed after retries. Falling back to Demo Mode.")
        return f"[DEMO FALLBACK] Unable to reach Gemini API. Synthetic response generated for demo."

    def generate_json(self, prompt: str, system_instruction: str = "", demo_fallback: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
        """Generates structured JSON response with validation, retry and demo fallback."""
        if self.demo_mode:
            if demo_fallback is not None:
                demo_fallback["_meta"] = {
                    "source": "DEMO_MODE_MOCK",
                    "note": "Generated by Demo Mock Service. Supply a valid PRUNE_API_KEY in .env to use the Prune gateway."
                }
                return demo_fallback
            return {
                "_meta": {"source": "DEMO_MODE_MOCK"},
                "status": "demo_output",
                "message": "Demo response"
            }

        json_prompt = f"{prompt}\n\nIMPORTANT: Respond with pure, valid JSON ONLY. Do not include markdown preamble or explanations outside the JSON."
        full_prompt = f"{system_instruction}\n\n{json_prompt}" if system_instruction else json_prompt

        for attempt in range(3):
            try:
                response = self.client.generate_content(full_prompt)
                if response and response.text:
                    clean_text = self._clean_json_response(response.text)
                    parsed = json.loads(clean_text)
                    parsed["_meta"] = {"source": "GEMINI_LIVE_API"}
                    return parsed
            except json.JSONDecodeError as jde:
                logger.warning(f"Failed to parse JSON on attempt {attempt + 1}: {jde}")
            except Exception as e:
                logger.warning(f"Gemini request failed on attempt {attempt + 1}: {e}")
            time.sleep(1)

        # Fallback if live calls fail
        if demo_fallback is not None:
            demo_fallback["_meta"] = {
                "source": "DEMO_FALLBACK_AFTER_ERROR",
                "error": "Live Gemini request failed. Falling back to safe synthetic structure."
            }
            return demo_fallback
        return {
            "_meta": {"source": "DEMO_FALLBACK_AFTER_ERROR"},
            "error": "Failed to parse structured model response."
        }


# Global singleton instance
llm_service = LLMService()
