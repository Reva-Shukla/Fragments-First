def test_inactive_user_rejection(client, victim_token):
    """Verifies that a valid token cannot authenticate an inactive user."""
    from app.database.session import SessionLocal
    from app.models.user import User

    db = SessionLocal()
    try:
        user = db.query(User).filter(User.email == "victim_test@example.com").first()
        assert user is not None
        user.is_active = False
        db.commit()
    finally:
        db.close()

    try:
        resp = client.get(
            "/api/auth/me",
            headers={"Authorization": f"Bearer {victim_token}"}
        )
        assert resp.status_code == 401
    finally:
        db = SessionLocal()
        try:
            user = db.query(User).filter(User.email == "victim_test@example.com").first()
            assert user is not None
            user.is_active = True
            db.commit()
        finally:
            db.close()


def test_expired_token_rejection(client):
    """Verifies that expired JWT tokens are rejected with 401."""
    from datetime import timedelta
    from app.core.security import create_access_token

    expired_token = create_access_token(
        data={"sub": "fresh_user@example.com", "role": "victim", "id": 1},
        expires_delta=timedelta(seconds=-10)
    )

    resp = client.get("/api/auth/me", headers={"Authorization": f"Bearer {expired_token}"})
    assert resp.status_code == 401
    assert "expired" in resp.json()["detail"].lower()


def test_swagger_openapi_token_url_configuration(client):
    """Verifies OpenAPI schema correctly advertises /api/auth/token as the OAuth2 password tokenUrl."""
    resp = client.get("/openapi.json")
    assert resp.status_code == 200
    schema = resp.json()
    oauth2_scheme_info = schema["components"]["securitySchemes"]["OAuth2PasswordBearer"]
    assert oauth2_scheme_info["type"] == "oauth2"
    assert oauth2_scheme_info["flows"]["password"]["tokenUrl"] == "/api/auth/token"
